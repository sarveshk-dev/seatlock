-- SeatLock schema for Oracle Database (12c or newer; tested design target: XE 21c)
-- Run as the seatlock user:
--   sqlplus seatlock/SeatLock123@localhost:1521/XEPDB1 @database/schema.sql

-- Oracle has no DROP TABLE IF EXISTS (before 23c), so ignore "does not exist" errors.
BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
              'BOOKING_SEATS', 'BOOKINGS', 'SHOW_SEATS', 'SHOWS', 'MOVIES', 'USERS'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;
    END;
  END LOOP;
END;
/

CREATE TABLE users (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(80)  NOT NULL,
  email         VARCHAR2(120) NOT NULL,
  password_hash VARCHAR2(100) NOT NULL,
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE movies (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        VARCHAR2(120) NOT NULL,
  synopsis     VARCHAR2(400) NOT NULL,
  duration_min NUMBER(5)     NOT NULL,
  language     VARCHAR2(30)  NOT NULL,
  accent_color CHAR(7) DEFAULT '#F5B83D' NOT NULL
);

-- DATE in Oracle already holds date AND time (to the second). All values are stored in UTC.
CREATE TABLE shows (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movie_id    NUMBER NOT NULL,
  screen_name VARCHAR2(30) NOT NULL,
  starts_at   DATE NOT NULL,
  price       NUMBER(8,2) NOT NULL,
  CONSTRAINT fk_show_movie FOREIGN KEY (movie_id) REFERENCES movies(id) ON DELETE CASCADE
);
CREATE INDEX idx_show_movie_time ON shows (movie_id, starts_at);

-- One row per physical seat PER SHOW. This row is the unit we lock.
CREATE TABLE show_seats (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  show_id         NUMBER  NOT NULL,
  row_label       CHAR(1) NOT NULL,
  seat_number     NUMBER(3) NOT NULL,
  status          VARCHAR2(10) DEFAULT 'available' NOT NULL,
  held_by         NUMBER NULL,
  hold_expires_at DATE NULL,     -- UTC; a hold is "live" only while this is in the future
  CONSTRAINT ck_seat_status CHECK (status IN ('available', 'held', 'booked')),
  CONSTRAINT fk_seat_show FOREIGN KEY (show_id) REFERENCES shows(id) ON DELETE CASCADE,
  CONSTRAINT fk_seat_user FOREIGN KEY (held_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT uq_show_seat UNIQUE (show_id, row_label, seat_number)
);
-- Oracle best practice: index every foreign key column (avoids extra table-level locks).
CREATE INDEX idx_seat_held_by ON show_seats (held_by);
CREATE INDEX idx_hold_expiry  ON show_seats (status, hold_expires_at);

CREATE TABLE bookings (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      NUMBER NOT NULL,
  show_id      NUMBER NOT NULL,
  seat_labels  VARCHAR2(120) NOT NULL,     -- e.g. "C5, C6" (kept after cancellation for history)
  total_amount NUMBER(10,2) NOT NULL,
  status       VARCHAR2(10) DEFAULT 'confirmed' NOT NULL,
  payment_ref  VARCHAR2(40) NOT NULL,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT ck_booking_status CHECK (status IN ('confirmed', 'cancelled')),
  CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_booking_show FOREIGN KEY (show_id) REFERENCES shows(id)
);
CREATE INDEX idx_booking_user ON bookings (user_id, created_at);
CREATE INDEX idx_booking_show ON bookings (show_id);

-- Second line of defence: UNIQUE(show_seat_id) makes selling one seat twice impossible,
-- even if application logic had a bug.
CREATE TABLE booking_seats (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id   NUMBER NOT NULL,
  show_seat_id NUMBER NOT NULL,
  CONSTRAINT fk_bs_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
  CONSTRAINT fk_bs_seat    FOREIGN KEY (show_seat_id) REFERENCES show_seats(id),
  CONSTRAINT uq_one_active_booking_per_seat UNIQUE (show_seat_id)
);
CREATE INDEX idx_bs_booking ON booking_seats (booking_id);

EXIT;
